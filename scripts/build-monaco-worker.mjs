/**
 * Build the Monaco editor worker (src/client/monaco-worker.ts) into a
 * self-contained IIFE and embed its source text into
 * src/client/generated/monaco-worker-source.js, which the client bundle
 * imports and turns into a Blob-URL Worker at runtime (see
 * src/client/monacoWorkerBootstrap.ts).
 *
 * Runs automatically as part of `pnpm bundle` / `pnpm watch` before tsdown;
 * can also be run alone via `pnpm run build:worker`. Only needs to be
 * re-run when the monaco-editor dependency changes.
 */
import { spawnSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const tmpDir = path.join(root, 'lib', '.monaco-worker-tmp')
const tsdownBin = path.join(root, 'node_modules', '.bin', 'tsdown')
const configPath = path.join(root, 'scripts', 'tsdown.worker.config.ts')
const outDir = path.join(root, 'src', 'client', 'generated')
const outFile = path.join(outDir, 'monaco-worker-source.js')

// Fresh temp output dir so a stale chunk can never be embedded.
rmSync(tmpDir, { recursive: true, force: true })

const res = spawnSync(tsdownBin, ['--config', configPath], { stdio: 'inherit' })
if (res.status !== 0) {
  console.error('[build-monaco-worker] tsdown worker build failed')
  process.exit(res.status ?? 1)
}

const chunks = readdirSync(tmpDir).filter((f) => f.endsWith('.js'))
if (chunks.length !== 1) {
  console.error('[build-monaco-worker] expected exactly one .js chunk in the worker build, got:', chunks)
  process.exit(1)
}
const code = readFileSync(path.join(tmpDir, chunks[0]), 'utf8')

mkdirSync(outDir, { recursive: true })
writeFileSync(
  outFile,
  '/* GENERATED by scripts/build-monaco-worker.mjs — do not edit by hand.\n' +
    ' * Regenerate with: pnpm run build:worker (runs automatically in pnpm bundle / pnpm watch). */\n' +
    'export default ' + JSON.stringify(code) + '\n',
)

rmSync(tmpDir, { recursive: true, force: true })
console.log('[build-monaco-worker] embedded ' + (code.length / 1024).toFixed(0) + ' KB of Monaco worker source into src/client/generated/monaco-worker-source.js')
