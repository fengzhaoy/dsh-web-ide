/**
 * Generate src/client/generated/version.ts from package.json — the About
 * dialog reads IDE_VERSION through src/client/version.ts, so package.json
 * stays the single source of truth and the shipped bundle carries ONLY the
 * version string (importing package.json directly would inline the whole
 * manifest — deps, scripts — into the browser bundle).
 *
 * Runs as part of `pnpm bundle` / `pnpm watch` before tsdown.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
const outDir = path.join(root, 'src', 'client', 'generated')
const outFile = path.join(outDir, 'version.ts')

mkdirSync(outDir, { recursive: true })
writeFileSync(outFile, `// GENERATED by scripts/gen-version.mjs — do not edit.
/** Plugin version, inlined from package.json at build time. */
export const PKG_VERSION = ${JSON.stringify(pkg.version)} as const
`)
console.log(`[gen-version] ${pkg.version} → src/client/generated/version.ts`)
